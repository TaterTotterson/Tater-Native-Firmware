#!/usr/bin/env python3
"""Package explicitly built integration images without replacing production 1.1.1."""
import argparse
import hashlib
import json
import os
import struct
import subprocess
import tempfile
from pathlib import Path
import zlib

ROOT = Path(__file__).resolve().parents[1]
VERSIONS = {"legacy": 1, "aec4": 2, "aec4_beam": 3}

def linked_versions(executable):
    """Read the DFU identity from linked ELF symbols, not the shared source header."""
    tool = Path(os.environ.get("XMOS_TOOL_PATH", "/Applications/XMOS_XTC_15.3.1")) / "bin/xobjdump"
    versions = set()
    with tempfile.TemporaryDirectory() as temporary:
        subprocess.run([str(tool), "--split", "--split-dir", temporary, str(executable)],
                       check=True, capture_output=True)
        for path in Path(temporary).rglob("*"):
            if not path.is_file():
                continue
            data = path.read_bytes()
            if data[:6] != b"\x7fELF\x01\x01":
                continue
            offset = struct.unpack_from("<I", data, 32)[0]
            stride, count = struct.unpack_from("<HH", data, 46)
            sections = [struct.unpack_from("<10I", data, offset + i * stride)
                        for i in range(count)]
            for section in sections:
                if section[1] != 2:  # ELF32 SHT_SYMTAB
                    continue
                strings = sections[section[6]]
                names = data[strings[4]:strings[4] + strings[5]]
                for position in range(section[4], section[4] + section[5], section[9]):
                    name, address, size, _, _, index = struct.unpack_from("<IIIBBH", data, position)
                    if names[name:].split(b"\0", 1)[0] != b"dfu_servicer_read_cmd.version":
                        continue
                    assert size == 5 and index < len(sections)
                    containing = sections[index]
                    start = containing[4] + address - containing[3]
                    versions.add(tuple(data[start:start + size]))
    return versions


def source_digest():
    digest = hashlib.sha256()
    files = []
    for folder in ("satellite-xmos-firmware", "modules/fph", "scripts", "tests"):
        files.extend(p for p in (ROOT / folder).rglob("*")
                     if p.is_file() and p.suffix in (".c", ".cpp", ".h", ".cmake", ".py", ".sh", ".txt")
                     and "__pycache__" not in p.parts and p.name != "version.h")
    files.extend(ROOT / name for name in ("submodules.lock", "requirements.txt", "build_sat1_fixed_delay.sh", "CMakeLists.txt", "xmos_macros.cmake", "modules/CMakeLists.txt"))
    for path in sorted(files):
        digest.update(path.relative_to(ROOT).as_posix().encode() + b"\0" + path.read_bytes())
    return digest.hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("variants", nargs="*", choices=list(VERSIONS), default=list(VERSIONS))
    args = parser.parse_args()
    destination = ROOT.parent / "candidates"
    destination.mkdir(exist_ok=True)
    manifest_path = destination / "manifest.json"
    manifest = json.loads(manifest_path.read_text()) if manifest_path.exists() else {}
    source_sha256 = source_digest()
    for variant in args.variants:
        image = ROOT / f"build_{variant}/satellite1_firmware_fixed_delay.factory.bin"
        expected_version = (1, 2, 0, 4, VERSIONS[variant])
        executable = image.parent / "tile0_satellite1_firmware_fixed_delay.xe"
        if linked_versions(executable) != {expected_version}:
            raise SystemExit(f"Linked firmware identity mismatch: {variant}")
        data = image.read_bytes()
        md5 = hashlib.md5(data).hexdigest()
        expected_md5 = image.with_suffix(".md5").read_text().strip().split()[0]
        if md5 != expected_md5:
            raise SystemExit(f"Factory MD5 mismatch: {variant}")
        name = f"sat1_xmos_{variant}.bin.zlib"
        compressed = zlib.compress(data, 9)
        assert zlib.decompress(compressed) == data
        (destination / name).write_bytes(compressed)
        (destination / f"{variant}.h").write_text(
            "/* Generated by source/scripts/package_candidates.py. */\n#pragma once\n"
            f'#define SAT1_XMOS_ASSET "sat1_xmos_{variant}_bin_zlib"\n'
            "#define SAT1_DOA_RESOURCE_ID 233\n"
            "#define SAT1_XMOS_TARGET_MAJOR 1\n#define SAT1_XMOS_TARGET_MINOR 2\n"
            "#define SAT1_XMOS_TARGET_PATCH 0\n#define SAT1_XMOS_TARGET_PRERELEASE 4\n"
            f"#define SAT1_XMOS_TARGET_COUNTER {VERSIONS[variant]}\n"
            f"#define SAT1_XMOS_TARGET_IMAGE_SIZE {len(data)}U\n")
        manifest[variant] = {
            "version": f"1.2.0-dev.{VERSIONS[variant]}",
            "linked_version": list(expected_version),
            "local_source_sha256": source_sha256,
            "factory_bytes": len(data), "compressed_bytes": len(compressed),
            "factory_md5": md5, "factory_sha256": hashlib.sha256(data).hexdigest(),
            "compressed_sha256": hashlib.sha256(compressed).hexdigest(),
            "upstream_develop": "ace8050265f134c1e0442661c8a16866467c9e53",
            "compact_frames_pr132": None if variant == "legacy" else "208e0d3ea07c3d61ae306b0ddd980b45977b2a76",
            "fwk_voice": "74b9e2e2c4b747efe124f35a52e654e0a19b6c87",
            "protocol": "0x11", "doa_resource": 233,
            "hardware_validated": False,
        }
        print(f"{variant}: {len(data)} bytes, {len(compressed)} compressed, MD5 {md5}")
    manifest_path.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")

if __name__ == "__main__":
    main()
